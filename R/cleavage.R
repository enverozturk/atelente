# Reference-bound candidate cleavage evidence.
pm_neo_spanning_ratios <- function(evidence, measurements, abundance_type = NULL) {
  if (is.null(abundance_type)) {
    abundance_type <- if ("abundance" %in% measurements$abundance_type) "abundance" else "normalized"
  }
  # Grouped columns may summarize several samples and cannot establish co-measurement.
  samples <- measurements[measurements$abundance_type %in% intersect(abundance_type, c("abundance", "normalized")), ]
  keys <- c("site_id", "record_id", "accession", "bond_left", "bond_right")
  neo <- unique(evidence[evidence$is_candidate %in% TRUE & evidence$role %in% c("N", "C"),
                         c(keys, "role", "peptide_id"), drop = FALSE])
  span <- unique(evidence[evidence$role == "spanning", c("site_id", "peptide_id"), drop = FALSE])
  names(neo)[names(neo) == "peptide_id"] <- "neo_peptide_id"
  names(span)[2] <- "spanning_peptide_id"
  pairs <- merge(neo, span, by = "site_id", sort = FALSE)
  pairs <- pairs[pairs$neo_peptide_id != pairs$spanning_peptide_id, , drop = FALSE]
  empty <- cbind(pairs[FALSE, ], data.frame(source_column=character(), sample=character(),
    abundance_type=character(), neo_value=numeric(), spanning_value=numeric(), neo_status=character(),
    spanning_status=character(), ratio=numeric(), log2_ratio=numeric()))
  if (!nrow(samples) || !nrow(pairs)) return(empty)
  status <- samples$value_status
  observed <- status == "observed"
  status[observed & samples$value == 0] <- "zero"
  status[observed & samples$value < 0] <- "negative"
  samples$value_status <- status
  channels <- split(seq_len(nrow(samples)), samples$source_column)
  do.call(rbind, unname(lapply(channels, function(rows) {
    channel <- samples[rows, , drop = FALSE]
    n <- match(pairs$neo_peptide_id, channel$peptide_id)
    s <- match(pairs$spanning_peptide_id, channel$peptide_id)
    stopifnot(!anyDuplicated(channel$peptide_id), !anyNA(n), !anyNA(s))
    out <- pairs
    out$source_column <- channel$source_column[1]
    out$sample <- channel$measurement_label[1]
    out$abundance_type <- channel$abundance_type[1]
    out$neo_value <- channel$value[n]
    out$spanning_value <- channel$value[s]
    out$neo_status <- channel$value_status[n]
    out$spanning_status <- channel$value_status[s]
    usable <- out$neo_status == "observed" & out$spanning_status == "observed"
    out$ratio <- NA_real_
    out$log2_ratio <- NA_real_
    out$log2_ratio[usable] <- log2(out$neo_value[usable]) - log2(out$spanning_value[usable])
    linear <- out$neo_value[usable] / out$spanning_value[usable]
    linear[!is.finite(linear) | linear == 0] <- NA_real_
    out$ratio[usable] <- linear
    out
  })))
}

# All channels in a ratio export contain the same observation pairs.
pm_neo_spanning_contrasts <- function(ratios, design) {
  samples <- design$samples[design$samples$Use == "Yes", , drop = FALSE]
  keys <- c("site_id", "record_id", "accession", "bond_left", "bond_right", "role",
            "neo_peptide_id", "spanning_peptide_id")
  pairs <- unique(ratios[keys])
  # site_id and both observation IDs are generated by the mapper.
  pair_key <- function(x) paste(x$site_id, x$role, x$neo_peptide_id, x$spanning_peptide_id, sep = "/")
  pair_ids <- if (nrow(pairs)) match(pair_key(ratios), pair_key(pairs)) else integer()
  by_condition <- function(condition) {
    cols <- samples[["Peptide column"]][samples$Condition == condition]
    take <- ratios$source_column %in% cols
    x <- ratios[take, , drop = FALSE]
    group <- pair_ids[take]
    count <- function(keep) tabulate(group[keep], nbins = nrow(pairs))
    usable <- is.finite(x$log2_ratio)
    n <- count(usable)
    mean_log <- rep(NA_real_, nrow(pairs))
    if (any(usable)) {
      totals <- rowsum(x$log2_ratio[usable], group[usable])
      idx <- as.integer(rownames(totals))
      mean_log[idx] <- totals[, 1] / n[idx]
    }
    stopifnot(all(count(rep(TRUE, nrow(x))) == length(cols)))
    data.frame(samples=rep(length(cols), nrow(pairs)), neo=count(x$neo_status == "observed"),
      spanning=count(x$spanning_status == "observed"), usable_pairs=n, mean_log2_ratio=mean_log,
      neo_missing=count(x$neo_status == "missing"))
  }
  contrasts <- design$comparisons
  conditions <- unique(c(contrasts$Treatment, contrasts$Control))
  summaries <- setNames(lapply(conditions, by_condition), conditions)
  output <- lapply(seq_len(nrow(contrasts)), function(i) {
    treatment <- contrasts$Treatment[i]
    control <- contrasts$Control[i]
    a <- summaries[[treatment]]
    b <- summaries[[control]]
    effect <- a$mean_log2_ratio - b$mean_log2_ratio
    fc <- 2^effect
    fc[!is.finite(fc) | fc == 0] <- NA_real_
    status <- rep("insufficient_coquantification", nrow(pairs))
    status[is.finite(effect)] <- "quantified_in_both"
    # Reserve one-condition calls for missing neo values with measured spanning
    # in every opposite-condition sample. Zero and invalid inputs are distinct.
    status[a$usable_pairs > 0 & b$neo_missing == b$samples & b$spanning == b$samples] <- "neo_quantified_only_in_treatment"
    status[b$usable_pairs > 0 & a$neo_missing == a$samples & a$spanning == a$samples] <- "neo_quantified_only_in_control"
    names(a) <- paste0("treatment_", names(a))
    names(b) <- paste0("control_", names(b))
    data.frame(pairs, comparison=rep(contrasts$Name[i], nrow(pairs)),
      treatment=rep(treatment, nrow(pairs)), control=rep(control, nrow(pairs)),
      a, b, log2_fc=effect, fold_change=fc, status=status)
  })
  do.call(rbind, output)
}

pm_cleavage_profile <- function(profile) {
  if (!is.list(profile)) stop("cleavage must be an explicit profile object.")
  if (is.null(profile$enzyme) || length(profile$enzyme) != 1L || !profile$enzyme %in% c("trypsin", "unknown"))
    stop("cleavage.enzyme must be trypsin or unknown.")
  if (profile$enzyme == "trypsin" &&
      (!is.logical(profile$lysine_blocked) || length(profile$lysine_blocked) != 1L || is.na(profile$lysine_blocked)))
    stop("Specify cleavage.lysine_blocked as true or false for trypsin.")
  if (is.null(profile$pre_digest_n_label)) profile$pre_digest_n_label <- NULL
  if (!is.null(profile$pre_digest_n_label) &&
      (!is.character(profile$pre_digest_n_label) || length(profile$pre_digest_n_label) != 1L ||
       !nzchar(trimws(profile$pre_digest_n_label)))) stop("pre_digest_n_label must be an exact modification name.")
  profile$expected_rule <- if (profile$enzyme == "unknown") "unknown" else
    if (isTRUE(profile$lysine_blocked)) "R, except before P" else "K or R, except before P"
  profile$processing_annotations <- "Not supplied; candidates may include normal protein processing."
  if (!is.null(profile$analysis_scope) && !identical(profile$analysis_scope,"specificity_v3"))
    stop("Supported analysis_scope is specificity_v3; omit it to reproduce the legacy scope.")
  profile
}

# Specificity describes one placement under the declared analytical digestion.
# It does not establish the origin/timing of an end or replace processing evidence.
pm_placement_specificity <- function(termini) {
  empty <- data.frame(placement_id=character(),peptide_id=character(),record_id=integer(),accession=character(),
    start=integer(),end=integer(),specificity=character(),specific_terminus=character(),
    n_boundary_compatible=logical(),c_boundary_compatible=logical(),n_processing_context=character(),
    c_processing_context=character(),analysis_eligible=logical(),exclusion_reason=character())
  if (!nrow(termini)) return(empty)
  ids <- unique(termini$placement_id)
  # Vectorized: one N and one C row per placement, output in first-seen order.
  nn <- tabulate(match(termini$placement_id[termini$role=="N"],ids),length(ids))
  nc <- tabulate(match(termini$placement_id[termini$role=="C"],ids),length(ids))
  if (any(tabulate(match(termini$placement_id,ids),length(ids))!=2L) || any(nn!=1L) || any(nc!=1L))
    stop("Each placement requires one N and one C terminus.")
  rn <- which(termini$role=="N"); rn <- rn[match(ids,termini$placement_id[rn])]
  rc <- which(termini$role=="C"); rc <- rc[match(ids,termini$placement_id[rc])]
  # Protein boundaries and possible initial-M excision are valid natural
  # boundaries, but are not relabelled as experimentally confirmed processing.
  natural <- c("reference_end","possible_initiator_met_removal")
  cn <- termini$digestion_compatible[rn]; cn[termini$processing_status[rn] %in% natural] <- TRUE
  cc <- termini$digestion_compatible[rc]; cc[termini$processing_status[rc] %in% natural] <- TRUE
  known <- !is.na(cn) & !is.na(cc)
  n <- ifelse(known,as.integer(cn)+as.integer(cc),NA_integer_)
  specificity <- ifelse(!known,"unknown",ifelse(n==2L,"specific",ifelse(n==1L,"semi-specific","unspecific")))
  terminus <- ifelse(!known,"unknown",ifelse(n==2L,"both",ifelse(n==0L,"neither",ifelse(cn %in% TRUE,"N","C"))))
  data.frame(placement_id=ids,peptide_id=termini$peptide_id[rn],record_id=termini$record_id[rn],
    accession=termini$accession[rn],start=termini$start[rn],end=termini$end[rn],
    specificity=specificity,specific_terminus=terminus,
    n_boundary_compatible=cn,c_boundary_compatible=cc,
    n_processing_context=termini$processing_status[rn],c_processing_context=termini$processing_status[rc],
    analysis_eligible=!known | n>0L,
    exclusion_reason=ifelse(known & n==0L,"unspecific_under_declared_profile",""),
    stringsAsFactors=FALSE)
}

pm_n_label <- function(modifications, available, label) {
  if (is.null(label) || !isTRUE(available) || is.na(modifications)) return(NA)
  # A site's semicolon belongs to its bracketed modification, not a new modification.
  groups <- regmatches(modifications, gregexpr("(?:^|;)\\s*[^;\\[\\]]+\\[[^\\]]*\\]", modifications, perl = TRUE))[[1]]
  for (g in groups) {
    name <- trimws(sub("\\[.*$", "", sub("^;", "", g)))
    name <- sub("^[0-9]+x\\s*", "", name)
    sites <- trimws(strsplit(sub("^.*\\[([^]]*)\\]$", "\\1", g), ";", fixed = TRUE)[[1]])
    if (identical(name, label) && "N-Term" %in% sites) return(TRUE)
  }
  FALSE
}

pm_bond_context <- function(sequence, k) {
  n <- nchar(sequence)
  if (length(k) != 1L || is.na(k) || k != as.integer(k) || k < 1L || k >= n)
    stop("Cleavage bond must lie between residues 1 and protein length.")
  positions <- seq.int(k - 3L, k + 4L)
  residues <- vapply(positions, function(p) if (p < 1L || p > n) "-" else substr(sequence, p, p), character(1))
  list(residues = residues, context_display = paste0(paste0(residues[1:4], collapse = ""), "|", paste0(residues[5:8], collapse = "")),
       context_complete = all(positions >= 1L & positions <= n))
}

pm_terminal <- function(sequence, k, role, profile, n_label) {
  n <- nchar(sequence)
  reference_end <- k == 0L || k == n
  compatible <- if (reference_end || profile$enzyme == "unknown") NA else {
    residues <- if (profile$enzyme == "trypsin" && !isTRUE(profile$lysine_blocked)) c("K", "R") else "R"
    substr(sequence, k, k) %in% residues && substr(sequence, k + 1L, k + 1L) != "P"
  }
  met <- role == "N" && k == 1L && startsWith(sequence, "M")
  label_support <- role == "N" && isTRUE(n_label)
  candidate <- if (reference_end) FALSE else if (label_support) TRUE else if (is.na(compatible)) NA else !compatible
  reason <- if (reference_end) "reference_end" else paste(c(if (label_support) "pre_digest_N_label",
    if (isFALSE(compatible)) "non_digestion_compatible", if (is.na(compatible) && !label_support) "digestion_unknown"), collapse = ";")
  classification <- if (reference_end) "reference_end" else if (met) "processing_compatible" else
    if (isTRUE(candidate)) paste0("neo_", role, "_candidate") else if (isFALSE(candidate)) "digestion_compatible" else "unclassified"
  list(digestion_compatible = compatible, pre_digest_n_label = if (role == "N") n_label else NA,
    processing_status = if (reference_end) "reference_end" else if (met) "possible_initiator_met_removal" else "not_assessed",
    classification = classification, is_candidate = candidate, candidate_reason = reason)
}

# Vectorized pm_terminal over placements; element-wise identical to pm_terminal().
pm_terminal_vec <- function(sequence, k, role, profile, n_label) {
  n <- nchar(sequence)
  reference_end <- k == 0L | k == n
  compatible <- rep(NA, length(k))
  if (profile$enzyme != "unknown") {
    residues <- if (profile$enzyme == "trypsin" && !isTRUE(profile$lysine_blocked)) c("K", "R") else "R"
    test <- !reference_end
    compatible[test] <- substr(sequence[test], k[test], k[test]) %in% residues &
      substr(sequence[test], k[test] + 1L, k[test] + 1L) != "P"
  }
  met <- role == "N" & k == 1L & startsWith(sequence, "M")
  label_support <- role == "N" & n_label %in% TRUE
  candidate <- ifelse(reference_end, FALSE, ifelse(label_support, TRUE, ifelse(is.na(compatible), NA, !compatible)))
  parts <- cbind(ifelse(label_support, "pre_digest_N_label", ""),
                 ifelse(compatible %in% FALSE, "non_digestion_compatible", ""),
                 ifelse(is.na(compatible) & !label_support, "digestion_unknown", ""))
  joined <- apply(parts, 1L, function(x) paste(x[nzchar(x)], collapse = ";"))
  if (!length(k)) joined <- character()
  reason <- ifelse(reference_end, "reference_end", joined)
  classification <- ifelse(reference_end, "reference_end", ifelse(met, "processing_compatible",
    ifelse(candidate %in% TRUE, paste0("neo_", role, "_candidate"), ifelse(candidate %in% FALSE, "digestion_compatible", "unclassified"))))
  list(digestion_compatible = compatible, pre_digest_n_label = ifelse(role == "N", n_label, NA),
    processing_status = ifelse(reference_end, "reference_end", ifelse(met, "possible_initiator_met_removal", "not_assessed")),
    classification = classification, is_candidate = candidate, candidate_reason = reason)
}

pm_build_cleavage <- function(result, profile, reference_sha256) {
  if (!requireNamespace("digest", quietly = TRUE)) stop("Install digest for cleavage reference identity.")
  profile <- pm_cleavage_profile(profile)
  if (length(reference_sha256) != 1L || !grepl("^[0-9a-f]{64}$", reference_sha256)) stop("A FASTA SHA-256 is required.")
  m <- result$matches; p <- result$peptides; f <- result$fasta
  empty_terms <- data.frame(placement_id=character(),peptide_id=character(),record_id=integer(),accession=character(),start=integer(),end=integer(),role=character(),bond_left=integer(),bond_right=integer(),internal_bond=logical(),digestion_compatible=logical(),pre_digest_n_label=logical(),processing_status=character(),classification=character(),is_candidate=logical(),candidate_reason=character())
  termini <- empty_terms
  if (nrow(m)) {
    # One N and one C terminus per placement, interleaved N,C in match order.
    obs <- match(m$peptide_id, p$peptide_id)
    sequence <- f$sequence[match(m$record_id, f$record_id)]
    # The N-label call depends only on the observation; evaluate once per peptide.
    uobs <- unique(obs)
    ulabel <- vapply(uobs, function(j) pm_n_label(p$modifications[j], p$modifications_available[j],
      profile$pre_digest_n_label), logical(1))
    label <- ulabel[match(obs, uobs)]
    nm <- nrow(m); at <- as.vector(rbind(seq_len(nm), seq_len(nm)))
    role <- rep(c("N", "C"), nm)
    k <- as.vector(rbind(m$start - 1L, m$end))
    seq_at <- sequence[at]
    cl <- pm_terminal_vec(seq_at, k, role, profile, label[at])
    termini <- data.frame(placement_id = sprintf("placement_%08d", seq_len(nm))[at], peptide_id = m$peptide_id[at],
      record_id = m$record_id[at], accession = m$accession[at], start = m$start[at], end = m$end[at],
      role = role, bond_left = k, bond_right = k + 1L, internal_bond = k > 0L & k < nchar(seq_at),
      cl, stringsAsFactors = FALSE)
  }
  scoped <- identical(profile$analysis_scope,"specificity_v3")
  placements <- NULL
  if (scoped) {
    placements <- pm_placement_specificity(termini)
    at <- match(termini$placement_id,placements$placement_id)
    for (field in c("specificity","specific_terminus","analysis_eligible","exclusion_reason"))
      termini[[field]] <- placements[[field]][at]
    termini$is_candidate_before_scope <- termini$is_candidate
    termini$is_candidate[!termini$analysis_eligible] <- FALSE
    empty_terms <- termini[FALSE,,drop=FALSE]
  }
  seeds <- unique(termini[termini$internal_bond & termini$is_candidate %in% TRUE, c("record_id", "bond_left"), drop = FALSE])
  pos_names <- c("P4","P3","P2","P1","P1prime","P2prime","P3prime","P4prime")
  empty_sites <- data.frame(site_id=character(),reference_sha256=character(),record_id=integer(),accession=character(),sequence_sha256=character(),bond_left=integer(),bond_right=integer(),context_display=character(),context_complete=logical(),neo_n_count=integer(),neo_c_count=integer(),spanning_count=integer())
  for (nm in pos_names) empty_sites[[nm]] <- character()
  empty_evidence <- empty_terms; empty_evidence$site_id <- character()
  sites <- empty_sites; evidence <- empty_evidence
  ns <- nrow(seeds)
  if (ns) {
    # Vectorized over seeds. Evidence order is preserved: per seed, its eligible
    # internal ends in termini order, then its spanning placements in match order.
    rid <- seeds$record_id; k <- seeds$bond_left
    seed_key <- paste(rid, k, sep = "\r")
    site_id <- paste(reference_sha256, rid, k, sep = ":")
    fi <- match(rid, f$record_id); ref_seq <- f$sequence[fi]; ref_acc <- f$accession[fi]
    len <- nchar(ref_seq)
    if (anyNA(k) || any(k != as.integer(k)) || any(k < 1L) || any(k >= len))
      stop("Cleavage bond must lie between residues 1 and protein length.")
    # Ends: internal termini at a seed bond (scoped: analysis-eligible only).
    e_rows <- which(termini$internal_bond & (if (scoped) termini$analysis_eligible else TRUE))
    e_seed <- match(paste(termini$record_id[e_rows], termini$bond_left[e_rows], sep = "\r"), seed_key)
    e_rows <- e_rows[!is.na(e_seed)]; e_seed <- e_seed[!is.na(e_seed)]
    # Spans: placements on the same record covering bond k|k+1.
    seeds_by_record <- split(seq_len(ns), rid)
    m_by_record <- split(seq_len(nrow(m)), m$record_id)
    pairs <- lapply(names(seeds_by_record), function(r) {
      si <- seeds_by_record[[r]]; mi <- m_by_record[[r]]
      if (!length(mi)) return(NULL)
      cover <- outer(m$start[mi], k[si], "<=") & outer(m$end[mi], k[si] + 1L, ">=")
      hit <- which(cover, arr.ind = TRUE)
      if (!nrow(hit)) return(NULL)
      cbind(seed = si[hit[, 2L]], match = mi[hit[, 1L]])
    })
    pairs <- do.call(rbind, pairs)
    s_seed <- if (is.null(pairs)) integer() else unname(pairs[, "seed"])
    s_m <- if (is.null(pairs)) integer() else unname(pairs[, "match"])
    s_pid <- sprintf("placement_%08d", s_m)
    if (scoped && length(s_m)) {
      keep <- placements$analysis_eligible[match(s_pid, placements$placement_id)]
      s_seed <- s_seed[keep]; s_m <- s_m[keep]; s_pid <- s_pid[keep]
    }
    ends <- termini[e_rows, , drop = FALSE]
    ends$site_id <- site_id[e_seed]
    sp <- data.frame(placement_id=s_pid,peptide_id=m$peptide_id[s_m],record_id=rid[s_seed],
      accession=ref_acc[s_seed],start=m$start[s_m],end=m$end[s_m],role=rep("spanning",length(s_m)),
      bond_left=k[s_seed],bond_right=k[s_seed]+1L,internal_bond=rep(TRUE,length(s_m)),
      digestion_compatible=rep(NA,length(s_m)),pre_digest_n_label=rep(NA,length(s_m)),
      processing_status=rep("not_applicable",length(s_m)),classification=rep("spanning",length(s_m)),
      is_candidate=rep(FALSE,length(s_m)),candidate_reason=rep("",length(s_m)),site_id=site_id[s_seed],
      stringsAsFactors=FALSE)
    if (scoped) {
      at <- match(sp$placement_id, placements$placement_id)
      for (field in c("specificity","specific_terminus","analysis_eligible","exclusion_reason"))
        sp[[field]] <- placements[[field]][at]
      sp$is_candidate_before_scope <- rep(FALSE, nrow(sp))
      sp <- sp[, names(ends), drop = FALSE]
    }
    block_order <- order(c(e_seed, s_seed), c(rep(0L, length(e_seed)), rep(1L, length(s_seed))),
                         c(e_rows, s_m), method = "radix")
    evidence <- rbind(ends, sp)[block_order, , drop = FALSE]
    # Reproduce the row names of the former do.call(rbind, per-seed blocks):
    # ends keep their termini row names, each spanning block is numbered 1..n,
    # then make.unique(sep="") as in rbind.data.frame.
    type <- c(rep(0L, length(e_seed)), rep(1L, length(s_seed)))[block_order]
    seed_o <- c(e_seed, s_seed)[block_order]
    labels <- c(as.character(e_rows), rep("", length(s_seed)))[block_order]
    span_at <- which(type == 1L)
    if (length(span_at)) labels[span_at] <- as.character(stats::ave(span_at, seed_o[span_at], FUN = seq_along))
    rownames(evidence) <- make.unique(labels, sep = "")
    # Distinct peptides per seed and role.
    count_unique <- function(seed, peptide) {
      u <- !duplicated(paste(seed, peptide, sep = "\r"))
      tabulate(seed[u], ns)
    }
    nsel <- termini$role[e_rows] == "N" & termini$is_candidate[e_rows] %in% TRUE
    csel <- termini$role[e_rows] == "C" & termini$is_candidate[e_rows] %in% TRUE
    seq_hash <- vapply(unique(ref_seq), function(s) digest::digest(s, algo = "sha256", serialize = FALSE), character(1))
    offsets <- -3:4
    residues <- vapply(offsets, function(o) {
      p <- k + o; ok <- p >= 1L & p <= len
      ifelse(ok, substr(ref_seq, p, p), "-")
    }, character(ns))
    if (ns == 1L) residues <- matrix(residues, nrow = 1L)
    sites <- data.frame(site_id=site_id,reference_sha256=rep(reference_sha256,ns),record_id=rid,accession=ref_acc,
      sequence_sha256=unname(seq_hash[ref_seq]),bond_left=k,bond_right=k+1L,
      context_display=paste0(residues[,1],residues[,2],residues[,3],residues[,4],"|",residues[,5],residues[,6],residues[,7],residues[,8]),
      context_complete=(k - 3L) >= 1L & (k + 4L) <= len,
      neo_n_count=count_unique(e_seed[nsel], termini$peptide_id[e_rows][nsel]),
      neo_c_count=count_unique(e_seed[csel], termini$peptide_id[e_rows][csel]),
      spanning_count=count_unique(s_seed, m$peptide_id[s_m]),stringsAsFactors=FALSE)
    for (j in seq_len(8L)) sites[[pos_names[j]]] <- residues[, j]
  }
  result$cleavage <- list(sites=sites, evidence=evidence, termini=termini, profile=profile)
  if(scoped) {
    result$cleavage$placements <- placements
    result$cleavage$excluded_placements <- placements[!placements$analysis_eligible,,drop=FALSE]
  }
  result$settings$cleavage <- c(profile, list(reference_sha256=reference_sha256,
    candidate_policy="Internal non-digestion-compatible boundaries or explicit pre-digestion N-label; possible natural processing retained.",
    quantities="Linked through peptide_id; not copied or summed across sites or placements."))
  if(scoped) result$settings$cleavage$candidate_policy <- paste(
    "specificity_v3: retain specific/semi-specific placements and unknown-profile audit;",
    "exclude unspecific placements from candidate generation and all linked evidence.",
    "Pre-digestion label evidence remains separate; possible natural processing retained descriptively.")
  result
}
